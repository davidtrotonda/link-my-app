export const blogSeoSlugs = blogSeoPosts.map((post) => post.slug);

export function getBlogSeoMeta(slug, language = "en") {
  const post = blogSeoPosts.find((candidate) => candidate.slug === slug);
  if (!post) return null;
  const localized = post.translations?.[language];
  return {
    slug: post.slug,
    title: localized?.title || post.title,
    description: localized?.description || post.description,
    category: localized?.category || post.category,
    publishedAt: post.publishedAt,
    keywords: post.keywords || [],
  };
}
