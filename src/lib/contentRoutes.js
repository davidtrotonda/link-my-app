function contentPath(catalog, hubs, contentId, language = "en") {
  const slugs = catalog[contentId];
  const hub = hubs[language] || hubs.en;
  if (!slugs) return hub;
  return `${hub}/${slugs[language] || slugs.en}`;
}

function contentIdBySlug(catalog, slug, language = "en") {
  return (
    Object.entries(catalog).find(
      ([, slugs]) => (slugs[language] || slugs.en) === slug,
    )?.[0] || ""
  );
}

export function nichePath(nicheId, language = "en") {
  return contentPath(useCaseSlugs, useCaseHubRoutes, nicheId, language);
}

export function getNicheIdBySlug(slug, language = "en") {
  return contentIdBySlug(useCaseSlugs, slug, language);
}

export function howToPath(howToId, language = "en") {
  return contentPath(howToSlugs, howToHubRoutes, howToId, language);
}

export function getHowToIdBySlug(slug, language = "en") {
  return contentIdBySlug(howToSlugs, slug, language);
}
